// العدّاد التنازلي المشترك بين الأدلة وقائمة الأفلام: خانة لكل وحدة (يوم، ساعة، دقيقة، ثانية) والرقم فوق اسمها،
// حتى لا تلتصق الأرقام ببعضها أو بأرقام النص المجاور، ولا ينكسر رقم على سطرين. الحساب حتى منتصف ليل يوم الصدور بتوقيت الجهاز.
// الأيام تُحذف حين لا يبقى يوم كامل. ما مضى موعده يُعاد null ليكتب المستدعي «اليوم» بصيغته.
export function segs(date) {
  const ms = new Date(date + 'T00:00:00') - Date.now(); if (ms <= 0) return null;
  const s = Math.floor(ms / 1e3), d = Math.floor(s / 86400), p = n => String(n).padStart(2, '0');
  const u = (n, l) => `<span class="seg"><b>${n}</b><i>${l}</i></span>`;
  return (d ? u(d, 'يوم') : '') + u(p(Math.floor(s / 3600) % 24), 'ساعة') + u(p(Math.floor(s / 60) % 60), 'دقيقة') + u(p(s % 60), 'ثانية');
}
